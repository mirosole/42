#include "stack.h"

/*
** ПЛАН СОРТИРОВКИ O(n^2) ЧЕРЕЗ ЦИКЛИЧЕСКИ УБЫВАЮЩИЙ СТЕК B
**
** Это описание будущей реализации. Функция ниже пока является заготовкой:
** её цикл не изменяет A и при непустом A не завершится.
**
** 1. ВХОДНЫЕ УСЛОВИЯ И ЦЕЛЬ
**
** - A содержит уникальные int, B изначально пуст.
** - Проверка аргументов, диапазона int и дубликатов выполняется заранее.
** - Если нужны данные disorder, вычислить их до первой операции.
** - top обозначает вершину; в примерах она находится слева.
** - size должен совпадать с фактическим количеством узлов.
** - В результате A возрастает от вершины ко дну, а B пуст.
** - Для пустого A и A из одного элемента операции не нужны.
** - Если A уже возрастает и B пуст, можно сразу завершить сортировку.
**
** 2. КАКИМИ ОПЕРАЦИЯМИ МЕНЯТЬ СТЕКИ
**
** Алгоритм анализирует значения и позиции обычным обходом списка,
** а меняет порядок элементов только командами push_swap.
** Для этого варианта достаточно pb, rb, rrb и pa:
** - pb(a, b): перенести вершину A на вершину B;
** - rb(b): первый элемент B становится последним;
** - rrb(b): последний элемент B становится первым;
** - pa(a, b): перенести вершину B на вершину A.
** Собственные функции поиска и выбора команды допустимы.
** Запись content или перестановка узлов внутри самого алгоритма не нужна.
** Реализация команд отвечает за изменение стека и вывод названия команды
** с переводом строки. Анализ стека и выбор направления ничего не печатают.
**
** 3. ОСНОВНАЯ ИДЕЯ: B ВСЕГДА ЦИКЛИЧЕСКИ УБЫВАЕТ
**
** Пример обычного убывания: [9, 7, 4, 1].
** Пример циклического убывания: [4, 1, 9, 7].
** Во втором примере порядок тот же, изменилось только положение вершины.
** Если мысленно соединить последний элемент с первым, для двух и более
** уникальных значений будет ровно один переход вверх: минимум -> максимум.
** Все остальные переходы идут от большего значения к меньшему.
** Пустой стек и стек из одного элемента подходят как начальное состояние.
**
** ВАЖНО: циклическим является порядок значений, а не сам связный список.
** У последнего узла next остаётся NULL. Пару последний -> первый нужно
** проверить отдельно либо временно взять top как следующего кандидата.
** Реально соединять последний узел с top нельзя.
**
** 4. ПЕРЕНОС ИЗ A В B
**
** Пока A не пуст:
**   1) Прочитать value из вершины A.
**   2) Вызвать prepare_stack(b, value).
**   3) Выполнить ровно один pb(a, b).
**
** prepare_stack только вращает B; она не переносит value из A.
** После неё вершина A всё ещё содержит тот же value.
** После pb размер A уменьшается на один, размер B увеличивается на один.
** Новая вершина B содержит value, и циклическое убывание сохраняется.
** Поэтому следующая итерация снова получает подходящий стек B.
**
** 5. ЧТО ДЕЛАЕТ prepare_stack(b, value)
**
** Для B размера 0 или 1 ничего вращать не нужно: можно сразу выполнить pb.
** В остальных случаях сначала найти промежуток для нового значения.
** Проверять соседние значения current и next, включая последний -> первый.
**
** Обычный убывающий промежуток подходит, когда:
**   current > value && value > next.
** Например, между 7 и 4 можно вставить 6.
**
** Промежуток минимум -> максимум узнаётся по current < next.
** Он подходит для нового минимума или максимума, то есть когда:
**   value < current || value > next.
** Например, между 1 и 9 подходят 0 и 10.
** Сравнивать значения напрямую: разность может переполниться для int.
**
** Когда промежуток найден, на вершину нужно поднять именно next.
** Тогда current окажется последним, а pb вставит value между ними
** в циклическом порядке: current -> value -> next.
**
** Позиции считать с нуля от текущей вершины B.
** Если current имеет индекс i, целевая позиция pos = (i + 1) % size.
** Для пары последний -> первый это pos = 0: вращений не требуется.
** Для корректного B и уникального value подходящий промежуток существует.
** prepare_stack предполагает этот порядок; произвольный B она не сортирует.
**
** 6. ЧТО ВОЗВРАЩАЕТ choose_rotation(pos, size)
**
** Эта функция только выбирает команду, но сама стек не вращает.
** Она принимает целевую позицию и размер B и возвращает указатель
** на функцию с сигнатурой void command(t_stack *).
** Для B возможны два результата: rb или rrb.
** Такой указатель затем можно вызвать как rotation(b).
** Команды rb/rrb предназначены для B; для вращения A нужны ra/rra.
**
** При 0 <= pos < size:
** - чтобы поднять элемент через rb, нужно pos команд;
** - при pos > 0 через rrb нужно size - pos команд;
** - при pos == 0 ничего делать не нужно.
** Если pos <= size / 2, выбрать rb; иначе выбрать rrb.
** При равном расстоянии подойдёт любое направление, договоримся брать rb.
** Для size < 2 можно вернуть rb, но prepare_stack его вызывать не должна.
** Нельзя вычислять остаток по size, если size равен нулю.
**
** 7. КАК prepare_stack ВЫПОЛНЯЕТ ВРАЩЕНИЯ
**
** После поиска pos:
**   rotation = choose_rotation(pos, b->size);
**   steps = pos;
**   если rotation == rrb, steps = b->size - pos;
**   пока steps > 0:
**     вызвать rotation(b);
**     уменьшить steps на один.
**
** Размер B во время вращений не меняется. Целевую позицию и количество
** шагов достаточно вычислить один раз до цикла.
** После цикла prepare_stack возвращается; вызывающая функция делает pb.
**
** Пример: B = [9, 7, 4, 1], value = 6.
** Подходящая пара: 7 -> 4, целевая позиция элемента 4 равна 2.
** size = 4: два rb или два rrb, по договорённости выбираем rb.
** После первого rb: [7, 4, 1, 9].
** После второго rb: [4, 1, 9, 7].
** После pb: [6, 4, 1, 9, 7]. Циклическое убывание сохранено.
**
** Пример обратного направления: B = [9, 7, 4, 1], value = 2.
** Подходящая пара: 4 -> 1, pos = 3, size = 4.
** Выбираем один rrb вместо трёх rb.
** После rrb: [1, 9, 7, 4]. После pb: [2, 1, 9, 7, 4].
**
** 8. КОГДА A ОПУСТЕЛ: ПОДНЯТЬ МАКСИМУМ B НА ВЕРШИНУ
**
** Теперь все элементы находятся в B и циклически убывают.
** Найти позицию максимума через find_max_position(b).
** Выбрать rb или rrb через choose_rotation и выполнить нужное число шагов
** по той же формуле, что используется внутри prepare_stack.
** После этого B убывает уже линейно, например: [9, 7, 4, 1].
** Для этого этапа не нужно придумывать дополнительный value и вызывать
** prepare_stack: целевая позиция максимума уже известна.
**
** 9. ВЕРНУТЬ ВСЁ ИЗ B В A
**
** Пока B не пуст, выполнять pa(a, b), без дополнительных вращений.
** Из B последовательно выходят максимум, следующий по величине и так далее.
** Каждый меньший элемент становится новой вершиной A.
** Пример последовательных состояний A:
**   [] -> [9] -> [7, 9] -> [4, 7, 9] -> [1, 4, 7, 9].
** В конце B пуст, A возрастает, минимальное значение находится сверху.
**
** 10. ПОЧЕМУ ЭТО O(n^2) ПО МОДЕЛИ ЗАДАНИЯ
**
** Когда в B находится m элементов, подготовка требует не более
** floor(m / 2) вращений и затем одного pb.
** При переносе всех n элементов m растёт от 0 до n - 1.
** Сумма этих верхних границ вращений имеет порядок O(n^2).
** Затем нужны максимум floor(n / 2) вращений для выравнивания B
** и ровно n команд pa. Всего также выполняется n команд pb.
** Следовательно, верхняя граница количества команд равна O(n^2).
**
** Поиск позиции читает список и не добавляет команд push_swap.
** Это оценка количества команд, как требует документ, а не времени CPU.
** Если одна команда вращения обходит список за O(m), фактическое время
** всей реализации может достигать O(n^3), при O(n^2) выданных команд.
** Сам алгоритм обходится указателями, значениями и счётчиками: O(1)
** дополнительной памяти сверх узлов стеков, которые занимают O(n).
**
** 11. ЧТО ПРОВЕРИТЬ ПОСЛЕ САМОСТОЯТЕЛЬНОЙ РЕАЛИЗАЦИИ
**
** - Пустой A, один элемент, уже отсортированный A.
** - Вставка в пустой B и B из одного элемента.
** - Вставка между обычными соседями и между последним и первым.
** - Новое минимальное и новое максимальное значение.
** - pos == 0: ни одной команды вращения.
** - Позиции ближе к началу, ближе к концу и ровно посередине.
** - Отрицательные числа, INT_MIN и INT_MAX без арифметики над значениями.
** - После каждой пары prepare_stack + pb B циклически убывает.
** - В конце A возрастает, B пуст, ни одно значение не потеряно.
** - Выданные команды при повторном выполнении дают тот же результат.
*/

void	sort_stack_O2(t_stack *a, t_stack *b)
{
	// fill b with sorted values 
	while (a->size > 0)
	{
		t_list tmp = peek(a);
		prepare_b_for_push(b, *(int*)tmp.content); 
		pb(a, b); 
	}

	normilize_stack(b); 

	while (b->size > 0)
	{
		pa(a, b); 
	}
	free_stack(b); 
	
}

/* Accept an ordinary descending gap or the minimum-to-maximum gap. */
static int	can_insert_between(int current, int next, int value)
{
	if (current > value && next < value)
		return (1);
	if (current < next && (current > value || next < value))
		return (1);
	return (0);
}

void	prepare_b_for_push(t_stack *s, int value)
{
	t_list	*cur;
	size_t	depth;

	if (!s || !s->top || s->size <= 1)
		return ;
	depth = 1;
	cur = s->top;
	while (cur->next)
	{
		if (can_insert_between(*(int *)cur->content, *(int *)cur->next->content, value))
			break;
		depth++;
		cur = cur->next;
	}
	
	// проверка на нал потому что мы не обязательно дошли до конца
	// проверка первого и последнего элемента. Мы только сейчас получили к нему доступ

	if (cur->next == NULL && can_insert_between(*(int *)cur->content, *(int *)s->top->content, value))
		depth = 0;
	rotate_stack(s, depth);
}

void	rotate_stack(t_stack *s, size_t depth)
{
	size_t	i;

	if (depth <= s->size - depth)
	{
		i = depth;
		while (i > 0)
		{
			rb(s);
			i--;
		}
	}
	else
	{
		i = s->size - depth;
		while (i > 0)
		{
			rrb(s);
			i--;
		}
	}
}


void normilize_stack(t_stack *s)
{

	if(!s || !s->top || s->size <= 1)
		return; 
		
	int max = *(int *)s->top->content;
	int depth = 0;  
	int max_pos = 0;  
	
	t_list *cur = s->top; 

	while (cur)
	{
		if(max < *(int *)cur->content)
		{
			max = *(int *)cur->content; 
			max_pos = depth; 
		}
		depth++; 
		cur = cur->next; 
	}

	rotate_stack(s, max_pos); 
}